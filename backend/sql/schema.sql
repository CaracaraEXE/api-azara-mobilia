-- schema.sql — Esquema inicial de la migración JSON -> PostgreSQL.
-- Ejecutar UNA VEZ sobre azarae_db con el rol azarae_user.
-- Convención: snake_case en SQL; src/db/queries.js hará el mapeo a camelCase de la API.
--
-- Inventario real verificado en backend/src/data/ (2026-11-19):
--   4 secciones, 25 categorías, 450 ítems únicos, 462 filas en item_categorias
--   (438 ítems con 1 categoría + 12 con 2), 200 titulares en 17 ítems,
--   67 ítems con colección, 332 con PDF, 1 con linkPdfEn.
-- Esos números son el objetivo de la carga Fase 4.

BEGIN;

-- Registro de migraciones aplicadas. Se inserta al final de este mismo archivo.
CREATE TABLE IF NOT EXISTS schema_migrations (
  version text PRIMARY KEY,
  applied_at timestamptz NOT NULL DEFAULT now()
);

-- Una SECCIÓN corresponde a una carpeta de backend/src/data/.
-- slug es la clave natural porque ya es el valor que usa la API (?seccion=).
CREATE TABLE IF NOT EXISTS secciones (
  slug text PRIMARY KEY CHECK (slug = btrim(slug) AND slug <> ''),
  nombre text NOT NULL CHECK (length(btrim(nombre)) > 0)
);

-- Categoría real de navegación, SIEMPRE dentro de una sección.
-- El mismo nombre en dos secciones es válido (unicidad compuesta).
CREATE TABLE IF NOT EXISTS categorias (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  seccion_slug text NOT NULL REFERENCES secciones(slug) ON DELETE RESTRICT,
  nombre text NOT NULL CHECK (length(btrim(nombre)) > 0),
  slug text NOT NULL CHECK (slug = btrim(slug) AND slug <> ''),
  CONSTRAINT uq_categorias_seccion_nombre UNIQUE (seccion_slug, nombre),
  CONSTRAINT uq_categorias_seccion_slug UNIQUE (seccion_slug, slug)
);

-- Ítem del catálogo. El id del JSON (lib-abc123) se conserva como PK textual:
-- Redis (si se usa después) y los custom_id de Discord lo referencian por ese id.
-- coleccion se guarda como texto: es la serie hiperespecífica opcional del JSON.
CREATE TABLE IF NOT EXISTS items (
  id text PRIMARY KEY CHECK (id = btrim(id) AND id <> ''),
  seccion_slug text NOT NULL REFERENCES secciones(slug) ON DELETE RESTRICT,
  titulo text NOT NULL CHECK (length(btrim(titulo)) > 0),
  link_pdf text,
  imagen_portada text NOT NULL,
  autor text,
  anio smallint CHECK (anio IS NULL OR anio BETWEEN 1000 AND 2100),
  fecha_extraccion timestamptz NOT NULL,
  coleccion text,
  link_pdf_en text
);

-- Un ítem puede figurar en varias categorías (12 libros hoy).
-- La tabla de unión reemplaza al array `categorias[]` del JSON.
CREATE TABLE IF NOT EXISTS item_categorias (
  item_id text NOT NULL REFERENCES items(id) ON DELETE CASCADE,
  categoria_id bigint NOT NULL REFERENCES categorias(id) ON DELETE CASCADE,
  PRIMARY KEY (item_id, categoria_id)
);

-- Titulares de hemeroteca. `orden` preserva el orden del array original.
CREATE TABLE IF NOT EXISTS titulares (
  item_id text NOT NULL REFERENCES items(id) ON DELETE CASCADE,
  orden integer NOT NULL CHECK (orden >= 0),
  texto text NOT NULL CHECK (length(btrim(texto)) > 0),
  PRIMARY KEY (item_id, orden)
);

-- Índices básicos para los filtros que ya expone la API.
-- lower(titulo) porque normalizarBusqueda() pasa a minúsculas antes de buscar.
CREATE INDEX IF NOT EXISTS idx_items_seccion ON items (seccion_slug);
CREATE INDEX IF NOT EXISTS idx_items_coleccion ON items (coleccion)
  WHERE coleccion IS NOT NULL;
CREATE INDEX IF NOT EXISTS idx_items_titulo_lower ON items (lower(titulo));
CREATE INDEX IF NOT EXISTS idx_items_fecha_extraccion ON items (fecha_extraccion);
CREATE INDEX IF NOT EXISTS idx_item_categorias_categoria
  ON item_categorias (categoria_id);
CREATE INDEX IF NOT EXISTS idx_titulares_texto_lower ON titulares (lower(texto));

INSERT INTO schema_migrations (version)
VALUES ('001_initial')
ON CONFLICT DO NOTHING;

COMMIT;
